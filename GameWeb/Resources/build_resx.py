"""Builds Resources/SharedResource.<culture>.resx from translations.<culture>.py.

For each language, checks that every L["..."] key used in Components/ and Localization/ has a
translation, and warns about translations no longer used. Run from anywhere:
    python GameWeb/Resources/build_resx.py
"""
import glob
import importlib.util
import os
import re
import sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)

# culture -> (translations file, dictionary name)
LANGUAGES = {
    "zh-Hans": ("translations.zh-Hans.py", "ZH_HANS"),
    "zh-Hant": ("translations.zh-Hant.py", "ZH_HANT"),
}

# Keys used through variables rather than literals (catalog entries, wind names).
DYNAMIC_KEYS = [
    "Hong Kong Mahjong", "Four players, 136 tiles, one winning hand.",
    "Classic Cantonese rules with faan scoring. Play the computer straight away, or open a private room and send the link to three friends.",
    "4 players", "Xiangqi", "Chinese chess on the river board.",
    "Two generals, one river. Play a friend or the computer, from beginner level up.", "2 players",
    "Dou Dizhu", "Fight the landlord.", "Three players, one landlord. Bid, team up and empty your hand first.", "3 players",
    "East", "South", "West", "North",
    # Xiangqi piece names (XqText.PieceName)
    "General", "Advisor", "Elephant", "Horse", "Chariot", "Cannon", "Soldier",
    # Account emails (Accounts/AccountEmails.cs passes these keys as arguments)
    "Confirm your Jade Tables account", "Hello {0}, thanks for joining Jade Tables. Please confirm your email address:",
    "Confirm my email", "If you didn't create an account, you can ignore this email.",
    "Reset your Jade Tables password",
    "Hello {0}, someone (hopefully you) asked to reset the password for your Jade Tables account:",
    "If you didn't ask for this, you can ignore this email; your password stays the same. The link works for one day.",
]

out = sys.stdout.buffer


def say(text):
    out.write((text + "\n").encode("utf-8"))


def used_keys():
    pattern = re.compile(r'\b[Ll]\["((?:[^"\\]|\\.)*)"')
    keys = []
    files = glob.glob(os.path.join(PROJECT, "Components", "**", "*.razor"), recursive=True)
    files += glob.glob(os.path.join(PROJECT, "Localization", "*.cs"))
    files += glob.glob(os.path.join(PROJECT, "Accounts", "*.cs"))
    for f in files:
        text = open(f, encoding="utf-8-sig").read()
        for m in pattern.finditer(text):
            key = m.group(1).replace('\\"', '"')
            if key not in keys:
                keys.append(key)
    for key in DYNAMIC_KEYS:
        if key not in keys:
            keys.append(key)
    return keys


def load(file_name, var):
    spec = importlib.util.spec_from_file_location(var.lower(), os.path.join(HERE, file_name))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return getattr(module, var)


HEADER = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by build_resx.py from {source}. Edit that file, not this one. -->
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
'''

keys = used_keys()
failed = False
for culture, (file_name, var) in LANGUAGES.items():
    table = load(file_name, var)
    missing = [k for k in keys if k not in table]
    unused = [k for k in table if k not in keys]
    if missing:
        say("%s: missing translations:\n%s" % (culture, "\n".join("  " + k for k in missing)))
        failed = True
        continue
    if unused:
        say("%s: unused translations (kept):\n%s" % (culture, "\n".join("  " + k for k in unused)))
    lines = [HEADER.format(source=file_name)]
    for key in sorted(table):
        lines.append('  <data name="%s" xml:space="preserve"><value>%s</value></data>\n'
                     % (escape(key, {'"': "&quot;"}), escape(table[key])))
    lines.append("</root>\n")
    target = os.path.join(HERE, "SharedResource.%s.resx" % culture)
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.writelines(lines)
    say("%s: wrote %d strings to %s" % (culture, len(table), target))

sys.exit(1 if failed else 0)
